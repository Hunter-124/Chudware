"""clangd LSP launcher for the firmware code panel (T-C4).

clangd (Apache-2.0-WITH-LLVM-exception) is a SUBPROCESS tool — never linked.
A missing binary is graceful: :meth:`ClangdManager.start` returns ``None`` instead of
raising; :meth:`get_diagnostics` returns an empty list with a ``reason`` entry.

The manager is intentionally stateless between calls: :meth:`start` spawns a fresh
clangd process pointing at the project's ``compile_commands.json`` (generated by T-C2
CMake configure). The caller owns the ``subprocess.Popen`` handle and must close it when
done.

clangd does NOT surface as an MCP tool — it serves the app's code panel only.
"""
from __future__ import annotations

import json
import shutil
import subprocess
import time
from typing import Optional

_CLANGD_BINARY = "clangd"

# LSP message framing helpers
_CONTENT_TYPE = "Content-Type: application/vscode-jsonrpc; charset=utf-8\r\n"


def _lsp_message(payload: dict) -> bytes:
    """Encode a JSON-RPC message with the standard LSP header."""
    body = json.dumps(payload).encode("utf-8")
    header = f"Content-Length: {len(body)}\r\n\r\n".encode("ascii")
    return header + body


def _read_lsp_response(proc: subprocess.Popen, timeout_s: float = 5.0) -> Optional[dict]:
    """Read one LSP response from *proc.stdout*.

    Returns the parsed JSON object, or ``None`` on timeout / EOF / parse error.
    clangd uses ``Content-Length: N\\r\\n\\r\\n<body>`` framing.
    """
    import select
    deadline = time.perf_counter() + timeout_s
    header_bytes = b""

    # Read header (ends with \r\n\r\n)
    while b"\r\n\r\n" not in header_bytes:
        remaining = deadline - time.perf_counter()
        if remaining <= 0:
            return None
        if proc.stdout is None:
            return None
        # non-blocking read
        ready, _, _ = select.select([proc.stdout], [], [], min(remaining, 0.1))
        if not ready:
            continue
        chunk = proc.stdout.read(1)
        if not chunk:
            return None
        header_bytes += chunk

    header_str = header_bytes.decode("ascii", errors="replace")
    content_length = 0
    for line in header_str.split("\r\n"):
        if line.lower().startswith("content-length:"):
            try:
                content_length = int(line.split(":", 1)[1].strip())
            except ValueError:
                pass

    if content_length <= 0:
        return None

    # Read body
    body = b""
    while len(body) < content_length:
        remaining = deadline - time.perf_counter()
        if remaining <= 0:
            return None
        if proc.stdout is None:
            return None
        ready, _, _ = select.select([proc.stdout], [], [], min(remaining, 0.1))
        if not ready:
            continue
        chunk = proc.stdout.read(content_length - len(body))
        if not chunk:
            return None
        body += chunk

    try:
        return json.loads(body.decode("utf-8"))
    except json.JSONDecodeError:
        return None


class ClangdManager:
    """Launch and interact with a clangd LSP server (Apache-2.0-WITH-LLVM-exception).

    All methods degrade gracefully when clangd is absent or fails to start.

    Typical usage (caller manages the process lifetime)::

        mgr = ClangdManager()
        proc = mgr.start("/path/to/project", build_dir="/path/to/project/build")
        if proc is not None:
            diags = mgr.get_diagnostics("/path/to/project/src/main.c", proc)
            proc.terminate()
    """

    BINARY = _CLANGD_BINARY

    def start(
        self,
        project_dir: str,
        build_dir: Optional[str] = None,
        query_driver: str = "**/arm-none-eabi-*",
    ) -> Optional[subprocess.Popen]:
        """Launch clangd pointing at *project_dir*'s compile_commands.json.

        Args:
            project_dir: Project root (used as working directory).
            build_dir: Directory containing ``compile_commands.json``. If omitted,
                       ``<project_dir>/build`` is used (T-C2 CMake default).
            query_driver: Glob for cross-compiler drivers passed to
                          ``--query-driver`` (default covers arm-none-eabi).

        Returns:
            A live :class:`subprocess.Popen` with ``stdin``/``stdout`` pipes for LSP
            JSON-RPC, or ``None`` when clangd is not on PATH.
        """
        if not shutil.which(self.BINARY):
            return None

        resolved_build = build_dir or f"{project_dir}/build"
        cmd = [
            self.BINARY,
            f"--compile-commands-dir={resolved_build}",
            f"--query-driver={query_driver}",
            "--log=error",
        ]
        try:
            return subprocess.Popen(
                cmd,
                cwd=project_dir,
                stdin=subprocess.PIPE,
                stdout=subprocess.PIPE,
                stderr=subprocess.DEVNULL,
            )
        except (FileNotFoundError, OSError):
            return None

    def get_diagnostics(
        self,
        file_path: str,
        proc: Optional[subprocess.Popen] = None,
        timeout_s: float = 5.0,
    ) -> list[dict]:
        """Request diagnostics for *file_path* from a running clangd process.

        Sends ``initialize`` + ``textDocument/didOpen`` to *proc* and collects
        ``textDocument/publishDiagnostics`` notifications for up to *timeout_s* seconds.

        Args:
            file_path: Absolute path to the C/C++ source file to diagnose.
            proc: A live clangd Popen handle from :meth:`start`. If ``None``, attempts
                  to launch a temporary clangd instance (graceful if absent).
            timeout_s: How long to wait for diagnostics.

        Returns:
            List of LSP diagnostic dicts (``{range, severity, message, source}``), or
            ``[{"reason": "clangd_not_found"}]`` when clangd is absent.
        """
        own_proc = False
        if proc is None:
            import os
            project_dir = str(os.path.dirname(file_path))
            proc = self.start(project_dir)
            own_proc = True

        if proc is None:
            return [{"reason": "clangd_not_found: 'clangd' is not installed / not on PATH"}]

        try:
            return self._collect_diagnostics(file_path, proc, timeout_s)
        finally:
            if own_proc:
                try:
                    proc.terminate()
                except Exception:
                    pass

    def _collect_diagnostics(
        self, file_path: str, proc: subprocess.Popen, timeout_s: float
    ) -> list[dict]:
        """Internal: do the LSP handshake and collect publishDiagnostics."""
        import pathlib
        uri = pathlib.Path(file_path).as_uri()

        # 1. Initialize
        init_msg = {
            "jsonrpc": "2.0",
            "id": 1,
            "method": "initialize",
            "params": {
                "processId": None,
                "capabilities": {},
                "rootUri": pathlib.Path(file_path).parent.as_uri(),
            },
        }
        try:
            if proc.stdin is None:
                return []
            proc.stdin.write(_lsp_message(init_msg))
            proc.stdin.flush()
        except (BrokenPipeError, OSError):
            return []

        # Read initialize response (discard — we just need the handshake)
        _read_lsp_response(proc, timeout_s=min(timeout_s, 3.0))

        # 2. initialized notification
        init_done = {"jsonrpc": "2.0", "method": "initialized", "params": {}}
        try:
            proc.stdin.write(_lsp_message(init_done))
            proc.stdin.flush()
        except (BrokenPipeError, OSError):
            return []

        # 3. textDocument/didOpen
        try:
            source_text = pathlib.Path(file_path).read_text(encoding="utf-8", errors="replace")
        except OSError:
            source_text = ""

        open_msg = {
            "jsonrpc": "2.0",
            "method": "textDocument/didOpen",
            "params": {
                "textDocument": {
                    "uri": uri,
                    "languageId": "c",
                    "version": 1,
                    "text": source_text,
                }
            },
        }
        try:
            proc.stdin.write(_lsp_message(open_msg))
            proc.stdin.flush()
        except (BrokenPipeError, OSError):
            return []

        # 4. Collect publishDiagnostics notifications
        diagnostics: list[dict] = []
        deadline = time.perf_counter() + timeout_s
        while time.perf_counter() < deadline:
            remaining = deadline - time.perf_counter()
            if remaining <= 0:
                break
            msg = _read_lsp_response(proc, timeout_s=remaining)
            if msg is None:
                break
            if msg.get("method") == "textDocument/publishDiagnostics":
                params = msg.get("params", {})
                if params.get("uri") == uri:
                    diagnostics.extend(params.get("diagnostics", []))
                    break  # first matching notification is the one we want

        return diagnostics
