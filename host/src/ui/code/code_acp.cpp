bool jsonRpcId(const nlohmann::json& value, AcpRequestId& id) {
    if (value.is_number_unsigned()) {
        id = value.get<AcpRequestId>();
        return true;
    }
    if (value.is_number_integer()) {
        const auto signedId = value.get<std::int64_t>();
        if (signedId < 0) return false;
        id = static_cast<AcpRequestId>(signedId);
        return true;
    }
    return false;
}

bool classifyFrame(const nlohmann::json& object, AcpFrame& frame,
                   std::string& error) {
    if (!object.is_object()) {
        error = "ACP frame is not a JSON object";
        return false;
    }

    const auto idIt = object.find("id");
    const auto methodIt = object.find("method");
    const bool hasId = idIt != object.end();
    const bool hasMethod = methodIt != object.end();
    const bool hasResult = object.contains("result");
    const bool hasError = object.contains("error");

    if (hasId && (hasResult || hasError)) {
        if (hasResult && hasError) {
            error = "ACP response contains both result and error";
            return false;
        }
        if (!jsonRpcId(*idIt, frame.id)) {
            error = "ACP response has a non-numeric or negative id";
            return false;
        }
        frame.kind = AcpFrameKind::Response;
        frame.payload = hasResult ? object["result"] : nlohmann::json();
        frame.error = hasError ? object["error"] : nlohmann::json();
        return true;
    }

    if (hasMethod) {
        if (!methodIt->is_string()) {
            error = "ACP method is not a string";
            return false;
        }
        frame.method = methodIt->get<std::string>();
        const auto paramsIt = object.find("params");
        frame.payload = paramsIt != object.end() ? *paramsIt : nlohmann::json::object();
        if (hasId) {
            if (!jsonRpcId(*idIt, frame.id)) {
                error = "ACP request has a non-numeric or negative id";
                return false;
            }
            frame.kind = AcpFrameKind::Request;
        } else {
            frame.kind = AcpFrameKind::Notification;
        }
        return true;
    }

    error = "ACP frame is neither a response, request, nor notification";
    return false;
}

