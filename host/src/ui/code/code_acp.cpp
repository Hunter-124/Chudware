bool setCloseOnExec(int fd, std::string& err) {
    const int flags = fcntl(fd, F_GETFD);
    if (flags < 0 || fcntl(fd, F_SETFD, flags | FD_CLOEXEC) < 0) {
        err = std::string("fcntl(FD_CLOEXEC) failed: ") + std::strerror(errno);
        return false;
    }
    return true;
}

bool makePipe(int (&fds)[2], std::string& err) {
    if (::pipe(fds) != 0) {
        err = std::string("pipe() failed: ") + std::strerror(errno);
        return false;
    }
    if (!setCloseOnExec(fds[0], err) || !setCloseOnExec(fds[1], err)) {
        ::close(fds[0]);
        ::close(fds[1]);
        fds[0] = fds[1] = -1;
        return false;
    }
    return true;
}

void closeFd(int& fd) {
    if (fd >= 0) {
        ::close(fd);
        fd = -1;
    }
}

// A write to a closed pipe normally raises SIGPIPE before it can return EPIPE.
// Block and consume only the signal generated by this write, preserving the
// process-wide signal disposition and any SIGPIPE that was already pending.
ssize_t writeWithoutSigpipe(int fd, const void* data, std::size_t size) {
    sigset_t set;
    sigemptyset(&set);
    sigaddset(&set, SIGPIPE);

    sigset_t oldMask;
    if (pthread_sigmask(SIG_BLOCK, &set, &oldMask) != 0)
        return ::write(fd, data, size);

    sigset_t pending;
    sigpending(&pending);
    const bool wasPending = sigismember(&pending, SIGPIPE) == 1;
    const ssize_t result = ::write(fd, data, size);
    const int savedErrno = errno;
    if (result < 0 && savedErrno == EPIPE && !wasPending) {
        timespec timeout{};
        while (sigtimedwait(&set, nullptr, &timeout) < 0 && errno == EINTR) {
        }
    }
    pthread_sigmask(SIG_SETMASK, &oldMask, nullptr);
    errno = savedErrno;
    return result;
}

bool waitForChild(pid_t pid, std::chrono::milliseconds timeout) {
    const auto deadline = std::chrono::steady_clock::now() + timeout;
    for (;;) {
        int status = 0;
        const pid_t result = ::waitpid(pid, &status, WNOHANG);
        if (result == pid || (result < 0 && errno == ECHILD)) return true;
        if (result < 0 && errno != EINTR) return false;
        if (std::chrono::steady_clock::now() >= deadline) return false;
        std::this_thread::sleep_for(std::chrono::milliseconds(10));
    }
}

void reapChildBlocking(pid_t pid) {
    for (;;) {
        const pid_t result = ::waitpid(pid, nullptr, 0);
        if (result == pid || (result < 0 && errno == ECHILD)) return;
        if (result < 0 && errno == EINTR) continue;
        return;
    }
}

