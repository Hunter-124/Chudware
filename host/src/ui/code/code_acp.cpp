std::string windowsError(DWORD code) {
    char* buffer = nullptr;
    const DWORD size = FormatMessageA(
        FORMAT_MESSAGE_ALLOCATE_BUFFER | FORMAT_MESSAGE_FROM_SYSTEM |
            FORMAT_MESSAGE_IGNORE_INSERTS,
        nullptr, code, MAKELANGID(LANG_NEUTRAL, SUBLANG_DEFAULT),
        reinterpret_cast<char*>(&buffer), 0, nullptr);
    std::string message = size != 0 && buffer != nullptr
                              ? std::string(buffer, size)
                              : "Windows error " + std::to_string(code);
    if (buffer != nullptr) LocalFree(buffer);
    while (!message.empty() &&
           (message.back() == '\r' || message.back() == '\n' || message.back() == '.'))
        message.pop_back();
    return message;
}

bool widenUtf8(const std::string& input, std::wstring& output) {
    if (input.empty()) {
        output.clear();
        return true;
    }
    const int size = MultiByteToWideChar(CP_UTF8, MB_ERR_INVALID_CHARS,
                                         input.data(), static_cast<int>(input.size()),
                                         nullptr, 0);
    if (size <= 0) return false;
    output.resize(static_cast<std::size_t>(size));
    return MultiByteToWideChar(CP_UTF8, MB_ERR_INVALID_CHARS,
                               input.data(), static_cast<int>(input.size()),
                               output.data(), size) == size;
}

std::wstring quoteWindowsArgument(const std::wstring& argument) {
    std::wstring quoted;
    quoted.push_back(L'"');
    std::size_t backslashes = 0;
    for (const wchar_t ch : argument) {
        if (ch == L'\\') {
            ++backslashes;
            continue;
        }
        if (ch == L'"') {
            quoted.append(backslashes * 2 + 1, L'\\');
            quoted.push_back(L'"');
        } else {
            quoted.append(backslashes, L'\\');
            quoted.push_back(ch);
        }
        backslashes = 0;
    }
    quoted.append(backslashes * 2, L'\\');
    quoted.push_back(L'"');
    return quoted;
}

bool resolveWindowsExecutable(const std::string& executable,
                              std::wstring& resolved, std::string& err) {
    if (!executable.empty()) {
        if (!widenUtf8(executable, resolved)) {
            err = "ACP executable is not valid UTF-8";
            return false;
        }
        return true;
    }

    const wchar_t* name = L"chudcode";
    const DWORD needed = SearchPathW(nullptr, name, L".exe", 0, nullptr, nullptr);
    if (needed == 0) {
        err = "Could not resolve chudcode from PATH (" +
              windowsError(GetLastError()) + ")";
        return false;
    }
    std::vector<wchar_t> buffer(static_cast<std::size_t>(needed) + 1);
    const DWORD written = SearchPathW(nullptr, name, L".exe",
                                      static_cast<DWORD>(buffer.size()),
                                      buffer.data(), nullptr);
    if (written == 0 || written >= buffer.size()) {
        err = "Could not resolve chudcode from PATH (" +
              windowsError(GetLastError()) + ")";
        return false;
    }
    resolved.assign(buffer.data(), written);
    return true;
}

