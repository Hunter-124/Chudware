AcpClient::~AcpClient() { stop(); }

bool AcpClient::start(const std::string& executable, const std::string& cwd,
                      std::string& err) {
    stop();
    err.clear();
    {
        std::lock_guard<std::mutex> lock(queueMtx_);
        queue_.clear();
    }

#ifdef _WIN32
    std::wstring application;
    if (!resolveWindowsExecutable(executable, application, err)) return false;
    std::wstring childCwd;
    if (!widenUtf8(cwd, childCwd)) {
        err = "ACP working directory is not valid UTF-8";
        return false;
    }

    SECURITY_ATTRIBUTES attributes{};
    attributes.nLength = sizeof(attributes);
    attributes.bInheritHandle = TRUE;

    HANDLE stdoutRead = nullptr;
    HANDLE stdoutWrite = nullptr;
    HANDLE stdinRead = nullptr;
    HANDLE stdinWrite = nullptr;
    if (!CreatePipe(&stdoutRead, &stdoutWrite, &attributes, 0)) {
        err = "Could not create ACP stdout pipe (" + windowsError(GetLastError()) + ")";
        return false;
    }
    if (!CreatePipe(&stdinRead, &stdinWrite, &attributes, 0)) {
        err = "Could not create ACP stdin pipe (" + windowsError(GetLastError()) + ")";
        CloseHandle(stdoutRead);
        CloseHandle(stdoutWrite);
        return false;
    }
    if (!SetHandleInformation(stdoutRead, HANDLE_FLAG_INHERIT, 0) ||
        !SetHandleInformation(stdinWrite, HANDLE_FLAG_INHERIT, 0)) {
        err = "Could not make ACP parent pipe handles private (" +
              windowsError(GetLastError()) + ")";
        CloseHandle(stdoutRead);
        CloseHandle(stdoutWrite);
        CloseHandle(stdinRead);
        CloseHandle(stdinWrite);
        return false;
    }

    STARTUPINFOW startup{};
    startup.cb = sizeof(startup);
    startup.dwFlags = STARTF_USESTDHANDLES;
    startup.hStdInput = stdinRead;
    startup.hStdOutput = stdoutWrite;
    startup.hStdError = GetStdHandle(STD_ERROR_HANDLE);

    std::wstring command = quoteWindowsArgument(application) + L" acp";
    std::vector<wchar_t> commandBuffer(command.begin(), command.end());
    commandBuffer.push_back(L'\0');
    PROCESS_INFORMATION processInfo{};
    const BOOL created = CreateProcessW(
        application.c_str(), commandBuffer.data(), nullptr, nullptr, TRUE,
        CREATE_NO_WINDOW, nullptr, childCwd.empty() ? nullptr : childCwd.c_str(),
        &startup, &processInfo);
    const DWORD createError = GetLastError();
    CloseHandle(stdoutWrite);
    CloseHandle(stdinRead);
    if (!created) {
        err = "Could not launch ACP process (" + windowsError(createError) + ")";
        CloseHandle(stdoutRead);
        CloseHandle(stdinWrite);
        return false;
    }
    CloseHandle(processInfo.hThread);

    {
        std::lock_guard<std::mutex> lock(stateMtx_);
        childStdinWr_ = stdinWrite;
        childStdoutRd_ = stdoutRead;
        process_ = processInfo.hProcess;
        running_ = true;
        stopping_ = false;
    }
#else
    int stdoutPipe[2] = {-1, -1};
    int stdinPipe[2] = {-1, -1};
    int execPipe[2] = {-1, -1};
    if (!makePipe(stdoutPipe, err)) return false;
    if (!makePipe(stdinPipe, err)) {
        closeFd(stdoutPipe[0]);
        closeFd(stdoutPipe[1]);
        return false;
    }
    if (!makePipe(execPipe, err)) {
        closeFd(stdoutPipe[0]);
        closeFd(stdoutPipe[1]);
        closeFd(stdinPipe[0]);
        closeFd(stdinPipe[1]);
        return false;
    }

    const std::string program = executable.empty() ? "chudcode" : executable;
    const pid_t pid = ::fork();
    if (pid < 0) {
        err = std::string("Could not fork ACP process: ") + std::strerror(errno);
        closeFd(stdoutPipe[0]);
        closeFd(stdoutPipe[1]);
        closeFd(stdinPipe[0]);
        closeFd(stdinPipe[1]);
        closeFd(execPipe[0]);
        closeFd(execPipe[1]);
        return false;
    }
    if (pid == 0) {
        ::close(stdoutPipe[0]);
        ::close(stdinPipe[1]);
        ::close(execPipe[0]);
        int childError = 0;
        if (::dup2(stdinPipe[0], STDIN_FILENO) < 0 ||
            ::dup2(stdoutPipe[1], STDOUT_FILENO) < 0) {
            childError = errno;
        } else if (!cwd.empty() && ::chdir(cwd.c_str()) != 0) {
            childError = errno;
        }
        ::close(stdinPipe[0]);
        ::close(stdoutPipe[1]);
        if (childError == 0) {
            ::execlp(program.c_str(), program.c_str(), "acp",
                     static_cast<char*>(nullptr));
            childError = errno;
        }
        const ssize_t ignored = ::write(execPipe[1], &childError, sizeof(childError));
        (void)ignored;
        ::close(execPipe[1]);
        _exit(127);
    }

    closeFd(stdoutPipe[1]);
    closeFd(stdinPipe[0]);
    closeFd(execPipe[1]);
    int childError = 0;
    ssize_t execRead;
    do {
        execRead = ::read(execPipe[0], &childError, sizeof(childError));
    } while (execRead < 0 && errno == EINTR);
    closeFd(execPipe[0]);
    if (execRead != 0) {
        if (execRead < 0)
            err = std::string("Could not verify ACP exec: ") + std::strerror(errno);
        else
            err = std::string("Could not launch ACP process: ") +
                  std::strerror(childError);
        closeFd(stdoutPipe[0]);
        closeFd(stdinPipe[1]);
        reapChildBlocking(pid);
        return false;
    }

    const int flags = fcntl(stdoutPipe[0], F_GETFL);
    if (flags < 0 || fcntl(stdoutPipe[0], F_SETFL, flags | O_NONBLOCK) < 0) {
        err = std::string("Could not configure ACP stdout: ") + std::strerror(errno);
        closeFd(stdinPipe[1]);
        ::kill(pid, SIGKILL);
        reapChildBlocking(pid);
        closeFd(stdoutPipe[0]);
        return false;
    }

    {
        std::lock_guard<std::mutex> lock(stateMtx_);
        childStdinWr_ = stdinPipe[1];
        childStdoutRd_ = stdoutPipe[0];
        process_ = static_cast<int>(pid);
        running_ = true;
        stopping_ = false;
    }
#endif

    try {
        reader_ = std::thread(&AcpClient::readerMain, this);
    } catch (const std::system_error& exception) {
        err = std::string("Could not start ACP reader thread: ") + exception.what();
        stop();
        return false;
    }
    return true;
}

void AcpClient::stop() {
    {
        std::lock_guard<std::mutex> lock(stateMtx_);
#ifdef _WIN32
        const bool idle = process_ == nullptr && childStdinWr_ == nullptr &&
                          childStdoutRd_ == nullptr && !reader_.joinable();
#else
        const bool idle = process_ < 0 && childStdinWr_ < 0 &&
                          childStdoutRd_ < 0 && !reader_.joinable();
#endif
        if (idle) {
            running_ = false;
            stopping_ = false;
            return;
        }
        if (stopping_) return;
        stopping_ = true;
        running_ = false;
    }

    // Serialize the EOF-producing close with all writes.
    {
        std::lock_guard<std::mutex> writeLock(writeMtx_);
        std::lock_guard<std::mutex> stateLock(stateMtx_);
#ifdef _WIN32
        if (childStdinWr_ != nullptr) {
            CloseHandle(static_cast<HANDLE>(childStdinWr_));
            childStdinWr_ = nullptr;
        }
#else
        closeFd(childStdinWr_);
#endif
    }

#ifdef _WIN32
    HANDLE process = nullptr;
    {
        std::lock_guard<std::mutex> lock(stateMtx_);
        process = static_cast<HANDLE>(process_);
    }
    if (process != nullptr) {
        DWORD wait = WaitForSingleObject(process,
                                         static_cast<DWORD>(kGracefulStopWindow.count()));
        if (wait == WAIT_TIMEOUT) {
            TerminateProcess(process, 1);
            WaitForSingleObject(process, 2000);
        }
        {
            std::lock_guard<std::mutex> lock(stateMtx_);
            process_ = nullptr;
        }
    }
#else
    pid_t pid = -1;
    {
        std::lock_guard<std::mutex> lock(stateMtx_);
        pid = static_cast<pid_t>(process_);
    }
    if (pid >= 0) {
        bool reaped = waitForChild(pid, kGracefulStopWindow);
        if (!reaped) {
            if (::kill(pid, SIGTERM) != 0 && errno == ESRCH) reaped = true;
            if (!reaped) reaped = waitForChild(pid, kTerminateStopWindow);
        }
        if (!reaped) {
            if (::kill(pid, SIGKILL) == 0 || errno == ESRCH)
                reapChildBlocking(pid);
            else
                reapChildBlocking(pid);
        }
        {
            std::lock_guard<std::mutex> lock(stateMtx_);
            process_ = -1;
        }
    }
#endif

    if (reader_.joinable()) reader_.join();

#ifdef _WIN32
    HANDLE stdoutRead = nullptr;
    {
        std::lock_guard<std::mutex> lock(stateMtx_);
        stdoutRead = static_cast<HANDLE>(childStdoutRd_);
        childStdoutRd_ = nullptr;
        stopping_ = false;
    }
    if (stdoutRead != nullptr) CloseHandle(stdoutRead);
    if (process != nullptr) CloseHandle(process);
#else
    {
        std::lock_guard<std::mutex> lock(stateMtx_);
        closeFd(childStdoutRd_);
        stopping_ = false;
    }
#endif
}

bool AcpClient::running() const {
    std::lock_guard<std::mutex> lock(stateMtx_);
    return running_ && !stopping_;
}

bool AcpClient::request(const std::string& method, const nlohmann::json& params,
                        AcpRequestId& id, std::string& err) {
    {
        std::lock_guard<std::mutex> lock(stateMtx_);
        if (nextId_ == 0) {
            err = "ACP request id space is exhausted";
            id = 0;
            return false;
        }
        id = nextId_;
        nextId_ = id == std::numeric_limits<AcpRequestId>::max() ? 0 : id + 1;
    }
    return writeFrame({{"jsonrpc", "2.0"}, {"id", id},
                       {"method", method}, {"params", params}}, err);
}

bool AcpClient::notify(const std::string& method, const nlohmann::json& params,
                       std::string& err) {
    return writeFrame({{"jsonrpc", "2.0"}, {"method", method},
                       {"params", params}}, err);
}

bool AcpClient::respond(AcpRequestId id, const nlohmann::json& result,
                        std::string& err) {
    return writeFrame({{"jsonrpc", "2.0"}, {"id", id}, {"result", result}}, err);
}

bool AcpClient::respondError(AcpRequestId id, int code,
                             const std::string& message, std::string& err) {
    return writeFrame({{"jsonrpc", "2.0"}, {"id", id},
                       {"error", {{"code", code}, {"message", message}}}}, err);
}

bool AcpClient::writeFrame(const nlohmann::json& frame, std::string& err) {
    std::string bytes;
    try {
        bytes = frame.dump();
    } catch (const std::exception& exception) {
        err = std::string("Could not serialize ACP frame: ") + exception.what();
        return false;
    }
    bytes.push_back('\n');

    std::lock_guard<std::mutex> writeLock(writeMtx_);
#ifdef _WIN32
    HANDLE input = nullptr;
    {
        std::lock_guard<std::mutex> lock(stateMtx_);
        if (!running_ || stopping_ || childStdinWr_ == nullptr) {
            err = "ACP process is not running";
            return false;
        }
        input = static_cast<HANDLE>(childStdinWr_);
    }
    std::size_t offset = 0;
    while (offset < bytes.size()) {
        const std::size_t remaining = bytes.size() - offset;
        const DWORD chunk = static_cast<DWORD>(std::min<std::size_t>(
            remaining, std::numeric_limits<DWORD>::max()));
        DWORD written = 0;
        if (!WriteFile(input, bytes.data() + offset, chunk, &written, nullptr) ||
            written == 0) {
            err = "Could not write ACP frame (" + windowsError(GetLastError()) + ")";
            std::lock_guard<std::mutex> lock(stateMtx_);
            running_ = false;
            return false;
        }
        offset += written;
    }
#else
    int input = -1;
    {
        std::lock_guard<std::mutex> lock(stateMtx_);
        if (!running_ || stopping_ || childStdinWr_ < 0) {
            err = "ACP process is not running";
            return false;
        }
        input = childStdinWr_;
    }
    std::size_t offset = 0;
    while (offset < bytes.size()) {
        const std::size_t remaining = bytes.size() - offset;
        const std::size_t chunk = std::min<std::size_t>(
            remaining, static_cast<std::size_t>(SSIZE_MAX));
        const ssize_t written = writeWithoutSigpipe(input, bytes.data() + offset, chunk);
        if (written < 0) {
            if (errno == EINTR) continue;
            err = std::string("Could not write ACP frame: ") + std::strerror(errno);
            std::lock_guard<std::mutex> lock(stateMtx_);
            running_ = false;
            return false;
        }
        if (written == 0) {
            err = "Could not write ACP frame: zero-byte write";
            std::lock_guard<std::mutex> lock(stateMtx_);
            running_ = false;
            return false;
        }
        offset += static_cast<std::size_t>(written);
    }
#endif
    err.clear();
    return true;
}

void AcpClient::readerMain() {
    std::string buffered;
    char chunk[4096];
    bool unexpectedFailure = false;
    std::string failure;

    for (;;) {
#ifdef _WIN32
        HANDLE output = nullptr;
        HANDLE process = nullptr;
        bool stopping = false;
        {
            std::lock_guard<std::mutex> lock(stateMtx_);
            output = static_cast<HANDLE>(childStdoutRd_);
            process = static_cast<HANDLE>(process_);
            stopping = stopping_;
        }
        if (output == nullptr || (stopping && process == nullptr)) break;

        DWORD available = 0;
        if (!PeekNamedPipe(output, nullptr, 0, nullptr, &available, nullptr)) {
            const DWORD code = GetLastError();
            if (code != ERROR_BROKEN_PIPE && code != ERROR_PIPE_NOT_CONNECTED) {
                unexpectedFailure = !stopping;
                failure = "Could not read ACP stdout (" + windowsError(code) + ")";
            }
            break;
        }
        if (available == 0) {
            if (process != nullptr && WaitForSingleObject(process, 0) == WAIT_OBJECT_0) {
                // A final PeekNamedPipe above observed no buffered bytes after exit.
                break;
            }
            std::this_thread::sleep_for(kReaderPollInterval);
            continue;
        }
        const DWORD wanted = std::min<DWORD>(available, sizeof(chunk));
        DWORD received = 0;
        if (!ReadFile(output, chunk, wanted, &received, nullptr)) {
            const DWORD code = GetLastError();
            if (code != ERROR_BROKEN_PIPE && code != ERROR_PIPE_NOT_CONNECTED) {
                unexpectedFailure = !stopping;
                failure = "Could not read ACP stdout (" + windowsError(code) + ")";
            }
            break;
        }
        if (received == 0) break;
        buffered.append(chunk, received);
#else
        int output = -1;
        int process = -1;
        bool stopping = false;
        {
            std::lock_guard<std::mutex> lock(stateMtx_);
            output = childStdoutRd_;
            process = process_;
            stopping = stopping_;
        }
        if (output < 0 || (stopping && process < 0)) break;

        pollfd descriptor{};
        descriptor.fd = output;
        descriptor.events = POLLIN | POLLHUP;
        const int ready = ::poll(&descriptor, 1,
                                 static_cast<int>(kReaderPollInterval.count()));
        if (ready < 0) {
            if (errno == EINTR) continue;
            unexpectedFailure = !stopping;
            failure = std::string("Could not poll ACP stdout: ") + std::strerror(errno);
            break;
        }
        if (ready == 0) continue;
        const ssize_t received = ::read(output, chunk, sizeof(chunk));
        if (received < 0) {
            if (errno == EINTR || errno == EAGAIN || errno == EWOULDBLOCK) continue;
            unexpectedFailure = !stopping;
            failure = std::string("Could not read ACP stdout: ") + std::strerror(errno);
            break;
        }
        if (received == 0) break;
        buffered.append(chunk, static_cast<std::size_t>(received));
#endif

        for (;;) {
            const std::size_t newline = buffered.find('\n');
            if (newline == std::string::npos) break;
            std::string line = buffered.substr(0, newline);
            buffered.erase(0, newline + 1);
            if (!line.empty() && line.back() == '\r') line.pop_back();

            try {
                const nlohmann::json object = nlohmann::json::parse(line);
                AcpFrame frame;
                std::string classificationError;
                if (!classifyFrame(object, frame, classificationError)) {
                    queueTransportError(classificationError);
                    continue;
                }
                std::lock_guard<std::mutex> lock(queueMtx_);
                queue_.push_back(std::move(frame));
            } catch (const std::exception& exception) {
                queueTransportError(std::string("Malformed ACP JSON line: ") +
                                    exception.what());
            }
        }
    }

    if (!buffered.empty())
        queueTransportError("ACP stdout closed with an unterminated JSON line");
    if (unexpectedFailure) queueTransportError(failure);

    std::lock_guard<std::mutex> lock(stateMtx_);
    running_ = false;
}

void AcpClient::queueTransportError(const std::string& message) {
    AcpFrame frame;
    frame.kind = AcpFrameKind::Notification;
    frame.method = "$/transportError";
    frame.payload = {{"message", message}};
    std::lock_guard<std::mutex> lock(queueMtx_);
    queue_.push_back(std::move(frame));
}

std::vector<AcpFrame> AcpClient::drain() {
    std::vector<AcpFrame> frames;
    std::lock_guard<std::mutex> lock(queueMtx_);
    frames.swap(queue_);
    return frames;
}

