#!/usr/bin/env python3
"""Regenerate assets/dict/en_US.txt, the copilot composer's spell-check/autocomplete word list.

Source: SCOWL (Spell Checker Oriented Word Lists) 2020.12.07, the same lists the hunspell
en_US dictionary is built from, at size 60 (the size SCOWL recommends for spell checking).
SCOWL sizes are a commonness ladder (10 = the most common words), so the output keeps them as
`#tier N` sections and the composer ranks completions by tier. SCOWL does not order words
inside a size, so the ~1500 words ranked by the public-domain Moby Words II frequency lists
(FREQ.TXT, FREQ-INT.TXT) go first, as tiers 1-5 by rank. SCOWL's Copyright file is copied to
assets/dict/LICENSE-SCOWL.txt.

Possessives ("word's") are dropped: the checker strips a trailing 's itself. Contractions
("don't", "it's") are kept. Everything is lowercased; non-ASCII entries are dropped (the
composer only checks ASCII words). Hand-maintained engineering vocabulary lives in
assets/dict/engineering.txt and is not touched by this script.

Usage: python3 scripts/build_spell_dictionary.py [--scowl scowl.tar.gz] [--moby files.zip]
"""
from __future__ import annotations

import argparse
import hashlib
import io
import tarfile
import urllib.request
import zipfile
from pathlib import Path

SCOWL_URL = "https://downloads.sourceforge.net/wordlist/scowl-2020.12.07.tar.gz"
SCOWL_SHA256 = "5587667caa20c4891390c2d42dbb4d5c4c3f41bee77af1457ece3ba23fb859cc"
MOBY_URL = "https://www.gutenberg.org/files/3201/files.zip"
MOBY_SHA256 = "f65c21aebea7b94f6162058fe2e5438bd539062faf5bfddd66c61e56b0575953"
SCOWL_TIERS = (10, 20, 35, 40, 50, 55, 60)
# Moby frequency rank -> tier: ranks below 100 are tier 1, below 250 tier 2, and so on.
FREQ_TIERS = ((100, 1), (250, 2), (500, 3), (750, 4), (10**9, 5))
WORD_LISTS = ("words", "upper", "proper-names", "abbreviations")
OUT_DIR = Path(__file__).resolve().parent.parent / "assets" / "dict"

HEADER = """\
# Chudware spell-check dictionary (en_US). GENERATED by scripts/build_spell_dictionary.py from
# SCOWL 2020.12.07 size 60 (http://wordlist.aspell.net/), ordered by the Moby Words II
# frequency lists (public domain); do not edit by hand.
# `#tier N` starts a commonness section (lower = more common): 1-5 Moby frequency rank,
# 10-60 SCOWL size.
#
# Copyright 2000-2018 by Kevin Atkinson
#
# Permission to use, copy, modify, distribute and sell these word lists, the associated
# scripts, the output created from the scripts, and its documentation for any purpose is
# hereby granted without fee, provided that the above copyright notice appears in all copies
# and that both that copyright notice and this permission notice appear in supporting
# documentation. Kevin Atkinson makes no representations about the suitability of this array
# for any purpose. It is provided "as is" without express or implied warranty.
#
# SCOWL also incorporates public-domain and permissively licensed sources (Moby, 12Dicts,
# ENABLE, Ispell, ...); their notices are in LICENSE-SCOWL.txt next to this file.
"""


def fetch(url: str, sha256: str, local: str | None) -> bytes:
    if local:
        raw = Path(local).read_bytes()
    else:
        with urllib.request.urlopen(url, timeout=120) as resp:
            raw = resp.read()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != sha256:
        raise SystemExit(f"{url}: sha256 mismatch: {digest}")
    return raw


def scowl_tiers(raw: bytes) -> tuple[list[tuple[int, set[str]]], bytes]:
    """(SCOWL size -> words first listed at that size, SCOWL's Copyright file)."""
    members: dict[str, bytes] = {}
    copyright_text = b""
    with tarfile.open(fileobj=io.BytesIO(raw), mode="r:gz") as tar:
        for m in tar.getmembers():
            if not m.isfile():
                continue
            if "/final/" in m.name:
                members[m.name.rsplit("/", 1)[1]] = tar.extractfile(m).read()
            elif m.name.count("/") == 1 and m.name.endswith("/Copyright"):
                copyright_text = tar.extractfile(m).read()
    if not copyright_text:
        raise SystemExit("SCOWL tarball has no Copyright file")
    seen: set[str] = set()
    tiers: list[tuple[int, set[str]]] = []
    for tier in SCOWL_TIERS:
        words: set[str] = set()
        for region in ("english", "american"):
            for kind in WORD_LISTS + ("contractions",):
                data = members.get(f"{region}-{kind}.{tier}")
                if data is None:
                    continue
                for line in data.decode("latin-1").splitlines():
                    w = line.strip().lower()
                    if not w or not w.isascii() or w in seen:
                        continue
                    if kind != "contractions" and w.endswith("'s"):
                        continue
                    words.add(w)
        seen |= words
        tiers.append((tier, words))
    return tiers, copyright_text


def moby_ranks(raw: bytes) -> dict[str, int]:
    """Lowercase word -> best rank across Moby's FREQ.TXT and FREQ-INT.TXT."""
    ranks: dict[str, int] = {}
    with zipfile.ZipFile(io.BytesIO(raw)) as z:
        for name in z.namelist():
            if name.lower().rsplit("/", 1)[-1] not in ("freq.txt", "freq-int.txt"):
                continue
            lines = z.read(name).decode("latin-1").splitlines()[1:]   # title line
            for rank, line in enumerate(l for l in lines if l.strip()):
                w = line.split()[-1].lower()
                ranks[w] = min(ranks.get(w, rank), rank)
    return ranks


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--scowl", help="local copy of scowl-2020.12.07.tar.gz (skips download)")
    ap.add_argument("--moby", help="local copy of Gutenberg #3201 files.zip (skips download)")
    args = ap.parse_args()

    tiers, copyright_text = scowl_tiers(fetch(SCOWL_URL, SCOWL_SHA256, args.scowl))
    known = set().union(*(words for _, words in tiers))
    # Moby-ranked words that SCOWL lists move up into the frequency tiers.
    ranks = {w: r for w, r in moby_ranks(fetch(MOBY_URL, MOBY_SHA256, args.moby)).items()
             if w in known}
    sections: list[tuple[int, list[str]]] = []
    placed: set[str] = set()
    for limit, tier in FREQ_TIERS:
        words = {w for w, r in ranks.items() if r < limit and w not in placed}
        placed |= words
        sections.append((tier, sorted(words, key=lambda w: (ranks[w], w))))
    for tier, words in tiers:
        sections.append((tier, sorted(words - placed, key=lambda w: (len(w), w))))

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "LICENSE-SCOWL.txt").write_bytes(copyright_text)
    out = OUT_DIR / "en_US.txt"
    with out.open("w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER)
        for tier, words in sections:
            f.write(f"#tier {tier}\n")
            f.write("".join(w + "\n" for w in words))
    print(f"wrote {out} ({sum(len(w) for _, w in sections)} words)")


if __name__ == "__main__":
    main()
