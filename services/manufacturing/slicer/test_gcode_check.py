"""Hermetic consumer-visible preflight checks for annotated and ordinary G-code."""
from __future__ import annotations

import time
from pathlib import Path

import pytest

from .gcode_check import parse_gcode, verify_gcode


_START = 'G90\nM83\nG28\nM190 S60\nM109 S220\n'
_END = 'M104 S0\nM140 S0\n'


def _layer(z, role='Perimeter', x=10.0, length=20, height=.2):
    return (f';LAYER_CHANGE\n;Z:{z}\n;HEIGHT:{height}\n;TYPE:{role}\n;WIDTH:0.45\n'
            f'G1 Z{z}\nG1 X{x} Y10\nG1 X{x+length} Y10 E1\nG1 Y10.4 E.1\nG1 X{x} Y10.4 E1\n')


def _verify(tmp_path, text, **kwargs):
    path = tmp_path/'print.gcode'
    path.write_text(text)
    result = verify_gcode(path, nozzle_mm=.4, material='PLA', bed_polygon=[(0,0),(100,0),(100,100),(0,100)], max_height_mm=100, **kwargs)
    return {row['check']:row for row in result['checks']}, result


def test_supported_layers_pass_and_metadata(tmp_path):
    text = '; generated by PrusaSlicer 2.9.6\n'+_START+_layer(.2)+_layer(.4)+_END+'; filament used [g] = 1.24\n; estimated printing time (normal mode) = 1h 2m 3s\n'
    checks, result = _verify(tmp_path,text,expect_nozzle_c=220,expect_bed_c=60)
    assert checks['floating_extrusion']['status']=='pass'
    assert checks['heat_before_extrude']['status']=='pass'
    assert result['stats']['filament_g']==1.24
    assert result['stats']['print_time_s']==3723
    assert result['stats']['slicer']=='PrusaSlicer 2.9.6'


@pytest.mark.parametrize('role, expected', [('Perimeter','fail'),('Bridge infill','fail'),('Overhang perimeter','fail'),('Skirt/Brim','pass')])
def test_long_midair_hard_and_anchored_paths_fail(tmp_path,role,expected):
    checks, _ = _verify(tmp_path,_START+_layer(.2)+_layer(.4,role=role,x=60)+_END)
    floating = checks['floating_extrusion']
    assert floating['status']==expected
    if expected=='fail':
        category = 'hard' if role == 'Perimeter' else 'anchored'
        assert floating['metrics']['classes'][category]['max_run_mm']>10
        assert floating['regions'][0]['z_mm']==.4
        assert floating['regions'][0]['centroid'][0]>60
        assert floating['regions'][0]['type']==role


