def _line(z,role,x0,y0,x1,y1,*,extrusion_height=None):
    extra = f';HEIGHT:{extrusion_height}\n' if extrusion_height is not None else ''
    return (f';LAYER_CHANGE\n;Z:{z}\n;HEIGHT:0.2\n;TYPE:{role}\n{extra};WIDTH:0.45\n'
            f'G1 Z{z}\nG1 X{x0} Y{y0}\nG1 X{x1} Y{y1} E1\n')


def test_short_anchored_bridge_passes_and_span_limit_is_configurable(tmp_path):
    base = (_line(.2,'Perimeter',10,10,10,14)
            +'G1 X15 Y10\nG1 Y14 E1\n')
    short = _line(.4,'Bridge infill',10,14,15,14)
    checks, _ = _verify(tmp_path,_START+base+short+_END)
    assert checks['floating_extrusion']['status']=='pass'
    run = checks['floating_extrusion']['metrics']['classes']['anchored']['max_run_mm']
    assert 0 < run < 5
    spans = checks['floating_extrusion']['metrics']['classes']['anchored']['backed_bridge_spans']
    assert spans['count'] > 0
    assert spans['worst_span']['anchor_count'] == 2
    missing_anchors = _line(.4,'Bridge infill',60,10,64,10)
    checks, _ = _verify(tmp_path,_START+base+missing_anchors+_END,max_unanchored_mm=2)
    assert checks['floating_extrusion']['status']=='fail'


@pytest.mark.parametrize('base_role,upper_role', [
    ('Internal infill','Solid infill'),
    ('Support material','Support material interface'),
])
def test_intentional_gap_spans_over_sparse_three_mm_lines_are_informational(tmp_path,base_role,upper_role):
    base = _line(.2,base_role,10,10,30,10)+'G1 X10 Y13\nG1 X30 E1\n'
    upper = _line(.4,upper_role,20,10,20,13)
    checks, _ = _verify(tmp_path,_START+base+upper+_END)
    floating = checks['floating_extrusion']
    assert floating['status']=='pass'
    info = floating['metrics']['classes']['gap_spanning']['by_type'][upper_role]
    assert info['total_floating_area_mm2']>0
    assert info['max_run_mm']>0
    assert floating['regions']==[]


def test_thick_extrudate_reaches_older_contact_interface_without_changing_plane_height(tmp_path):
    base = _line(.2,'Support material interface',10,10,30,10)
    intervening = _line(.4,'Support material',60,10,64,10)
    object_layer = _line(.6,'Perimeter',10,10,30,10,extrusion_height=.4)
    text = _START+base+intervening+object_layer+'; support_material_contact_distance = 0.15\n'+_END
    checks, _ = _verify(tmp_path,text)
    # The intervening support line hangs within the bed drop allowance; what matters is
    # that the thick object extrudate finds the earlier interface across its contact gap.
    assert checks['floating_extrusion']['metrics']['classes']['hard']['by_type']['Perimeter']['total_floating_area_mm2']==0
    assert checks['layer_heights']['status']=='pass'


def test_long_two_ended_bridge_warns_for_sag_but_never_fails(tmp_path):
    base = _line(.2,'Perimeter',10,10,10,14)+'G1 X42 Y10\nG1 Y14 E1\n'
    bridge = _line(.4,'Bridge infill',10,14,42,14)
    checks, _ = _verify(tmp_path,_START+base+bridge+_END)
    row = checks['floating_extrusion']
    assert row['status']=='warn'
    assert 'long bridge, expect sag' in row['note']
    assert row['metrics']['classes']['anchored']['max_unanchored_run_mm']==0
    assert row['metrics']['classes']['anchored']['backed_bridge_spans']['max_span_mm']>25
    checks, _ = _verify(tmp_path,_START+base+bridge+_END,anchored_bridge_warn_mm=40)
    assert checks['floating_extrusion']['status']=='pass'


def test_hard_float_run_threshold_can_fail_without_large_area(tmp_path):
    text = _START+_layer(.2)+_line(.4,'Perimeter',60,10,62.1,10)+_END
    checks, _ = _verify(tmp_path,text)
    row = checks['floating_extrusion']
    assert row['metrics']['worst_layer_area_mm2']<2
    assert row['status']=='fail'
