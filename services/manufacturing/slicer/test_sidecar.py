from __future__ import annotations

import hashlib
from pathlib import Path

from services.manufacturing.slicer.contract import (
    Determinism,
    ModelRef,
    ProfileRef,
    SliceRefusal,
    SliceRequest,
    SliceResult,
)
from services.manufacturing.slicer.sidecar import SLICER_ENV_VAR, invoke_sidecar


FAKE_SLICER = Path(__file__).resolve().parents[3] / "fixtures/mfg/print/fake_slicer.py"


def _request(tmp_path: Path) -> SliceRequest:
    model = tmp_path / "cube.stl"
    model.write_bytes(b"solid cube\nendsolid cube\n")
    model_hash = hashlib.sha256(model.read_bytes()).hexdigest()
    return SliceRequest(
        project_id="project-1",
        project_rev=7,
        plate_id="plate-1",
        sidecar_build_id="fixture-build-1",
        profiles=(
            ProfileRef("printer", "printer", 1, "1" * 64),
            ProfileRef("filament", "pla", 3, "2" * 64),
            ProfileRef("process", "quality", 5, "3" * 64),
        ),
        models=(ModelRef("cube", str(model), model_hash),),
        determinism=Determinism(seed=8675309),
    )


def test_missing_binary_is_typed_refusal_naming_environment_variable(tmp_path: Path) -> None:
    result = invoke_sidecar(_request(tmp_path), tmp_path / "work", environ={})

    assert isinstance(result, SliceRefusal)
    assert result.code == "missing_slicer_binary"
    assert result.missing_prerequisite == SLICER_ENV_VAR
    assert SLICER_ENV_VAR in result.message


def test_identical_requests_have_identical_artifact_hash_and_provenance(tmp_path: Path) -> None:
    request = _request(tmp_path)
    first = invoke_sidecar(request, tmp_path / "work", binary=FAKE_SLICER)
    second = invoke_sidecar(request, tmp_path / "work", binary=FAKE_SLICER)

    assert isinstance(first, SliceResult)
    assert isinstance(second, SliceResult)
    assert first.artifact.sha256 == second.artifact.sha256
    assert first.provenance == second.provenance
    assert first.provenance.sidecar_version == "0.1.0-fixture"
    assert first.provenance.sidecar_commit == "4f81e8d11a2d7427953481df3b0545a193c4c78f"
    assert first.provenance.profile_hashes == {
        "printer:printer": "1" * 64,
        "filament:pla": "2" * 64,
        "process:quality": "3" * 64,
    }
    assert Path(first.artifact.path).read_text(encoding="utf-8").startswith(
        "; generated by chudware deterministic fake slicer\n"
    )
    work_dir = tmp_path / "work" / request.request_id
    assert (work_dir / "request.json").is_file()
    assert (work_dir / "cmd.txt").is_file()
    assert (work_dir / "stdout.log").is_file()
    assert (work_dir / "stderr.log").is_file()
    assert (work_dir / "result.json").is_file()


def test_malformed_sidecar_output_is_a_refusal(tmp_path: Path) -> None:
    result = invoke_sidecar(
        _request(tmp_path),
        tmp_path / "work",
        binary=FAKE_SLICER,
        environ={"CHUDWARE_FAKE_SLICER_MODE": "malformed"},
    )

    assert isinstance(result, SliceRefusal)
    assert result.code == "malformed_sidecar_output"
    assert "traceback" not in result.message.lower()
