"""Emit the VLM candidate go/no-go section into docs/RECOGNITION_RESIDUAL.md (T-H10 DoD 1).

Reproducible: re-run this script to regenerate the section (like tools/gsl_eval.py does for
the main report). It does NOT hand-edit the generated GNN region at the top of the file — it
replaces ONLY the content between the VLM markers, appending the section on first run. Run
with a served endpoint reachable to fill the candidate rows with MEASURED numbers; offline
they honestly read `pending-provision` with exact commands (never a fabricated score).

    python -m tools.flywheel.vlm.residual_report                      # offline: pending rows
    python -m tools.flywheel.vlm.residual_report --base-url http://127.0.0.1:1234/v1  # live
"""
from __future__ import annotations

import argparse
import os

from .candidate_eval import run_residual
from .candidates import CANDIDATES

_REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
DOC = os.path.join(_REPO, "docs", "RECOGNITION_RESIDUAL.md")
CORPUS = os.path.join(_REPO, "training", "corpora", "vlm", "v1")
BEGIN = "<!-- BEGIN T-H10 VLM RESIDUAL (generated by tools/flywheel/vlm/residual_report.py) -->"
END = "<!-- END T-H10 VLM RESIDUAL -->"


def _fmt(v):
    return "—" if v is None else v


def build_section(base_url: str) -> str:
    rep = run_residual(CORPUS, base_url=base_url)
    ceil = rep["deterministic_ceiling"]
    lines = [
        BEGIN, "",
        "## VLM candidate go/no-go (T-H10 v0 — offline vision track)", "",
        f"GENERATED by `tools/flywheel/vlm/residual_report.py` — re-run, do not hand-edit. "
        f"Corpus `{rep['corpus_dir']}` (synthetic, provenance=synthetic). "
        f"Generated: {rep['generated']}.", "",
        "**Locked division of labor:** the VLM proposes coarse, confidence-tiered claims; "
        "deterministic code verifies. Scoring is the T-H8 VLM bench (precision is king — one "
        "hallucination fails an example). **This section IS the residual measurement** that "
        "gates VLM training (RECOGNITION_RESIDUAL discipline).", "",
        "### Deterministic ceiling (MEASURED — the floor to beat)", "",
        f"| mean F1 | precision | recall | pass-rate | n |",
        f"|---|---|---|---|---|",
        f"| {ceil['mean_f1']} | {ceil['precision']} | {ceil['recall']} | {ceil['pass_rate']} | {ceil['n']} |",
        "",
        "### Candidate residuals (the 3 RATIFIED local models — Apache-2.0, run OFFLINE once provisioned)",
        "",
        "| candidate | status | mean F1 | precision | residual vs deterministic | verdict |",
        "|---|---|---|---|---|---|",
    ]
    for r in rep["candidates"]:
        status = "MEASURED" if r["available"] else "pending-provision"
        lines.append(
            f"| {r['candidate']} | {status} | {_fmt(r['mean_f1']) if r['available'] else '—'} "
            f"| {_fmt(r['precision']) if r['available'] else '—'} "
            f"| {_fmt(r['residual_over_deterministic'])} | {r['verdict']} |")
    lines += [
        "",
        "**GO/NO-GO rule:** a candidate is **GO** iff its zero-shot bench F1 beats the "
        "deterministic ceiling AND precision == 1.0 (kill-switch cond. 1: never lose to the "
        "fallback). Cond. 2 — beat the frontier-VLM-via-API **per dollar** — is pending "
        "offline (no API creds/network; owned by the T-H8 `frontier` row).", "",
        "**Zero-shot literature floors (REFERENCE only — not bench scores):**",
    ]
    for k, c in CANDIDATES.items():
        floor = ", ".join(f"{kk}={vv}" for kk, vv in c.lit_floor.items() if kk != "source")
        lines.append(f"- `{k}` ({c.display_name}): {floor} "
                     f"[{c.lit_floor.get('source','')}]")
    lines += [
        "",
        "**To fill the MEASURED rows** (foreman/Erik-authorized provisioning; NOT run in CI):",
        "```", rep["provision"].rstrip(), "```",
        "then `python -m tools.flywheel.vlm.residual_report --base-url http://127.0.0.1:1234/v1`.",
        "",
        "**Open gaps to re-verify before any training claim (recorded, not chat):**",
    ]
    for k, c in CANDIDATES.items():
        for g in c.unverified:
            lines.append(f"- `{k}`: {g}")
    lines += ["", END, ""]
    return "\n".join(lines)


def write(base_url: str, doc_path: str = DOC) -> str:
    section = build_section(base_url)
    with open(doc_path, encoding="utf-8") as f:
        content = f.read()
    if BEGIN in content and END in content:
        pre = content[: content.index(BEGIN)]
        post = content[content.index(END) + len(END):]
        content = pre + section.rstrip() + "\n" + post.lstrip("\n")
    else:
        content = content.rstrip() + "\n\n---\n\n" + section
    with open(doc_path, "w", encoding="utf-8") as f:
        f.write(content)
    return doc_path


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Emit the T-H10 VLM residual section.")
    ap.add_argument("--base-url", default="http://127.0.0.1:1234/v1")
    ap.add_argument("--print", action="store_true", help="print to stdout, do not write")
    args = ap.parse_args(argv)
    if args.print:
        print(build_section(args.base_url))
    else:
        print("wrote", write(args.base_url))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
