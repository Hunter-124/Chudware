#!/usr/bin/env python3
"""gen_tool_panel_tables.py — regenerate the Settings → AI → Tools offline
fallback catalog tables.

Outputs (both git-tracked):
  host/src/ui/tool_panel_tables.h              — C++ fallback tables
  host/src/ui/tool_panel_tables.snapshot.json  — the data the header renders from

Modes:
  emit (default)  — needs the runtime venv (`.venv-mcp/bin/python`): warms the
                    live tool registry, rebuilds the snapshot, re-renders the
                    header. Run this whenever MCP tools are added/renamed
                    (enforced by services/agent/test_tool_guidance.py).
  --check         — stdlib-only: re-renders the header FROM THE SNAPSHOT and
                    diffs it against the .h on disk. Wired into scripts/check.py
                    as the ``tool_panel_sync`` audit. (It checks snapshot⟷header
                    consistency; live-registry⟷snapshot drift is the pytest
                    test's job.)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
HEADER = REPO / "host/src/ui/tool_panel_tables.h"
SNAPSHOT = REPO / "host/src/ui/tool_panel_tables.snapshot.json"

DESC_MAX = 140


def _one_line(text: str) -> str:
    return " ".join((text or "").split())


def _truncate(text: str, limit: int = DESC_MAX) -> str:
    if len(text) <= limit:
        return text
    return text[:limit].rsplit(" ", 1)[0].rstrip(" ,;:") + " …"


def build_snapshot() -> dict:
    """Build {families, fam_tools, descs, guidance} from the LIVE registry
    (needs venv)."""
    sys.path.insert(0, str(REPO))
    from services.agent import agent_turn as at
    from services.agent.config import DEFAULT_TOOL_FAMILIES
    from services.agent.tool_guidance import (
        GUIDANCE_KEYS,
        PSEUDO_TOOLS,
        guidance_for,
    )
    from services.agent.tool_schemas import _FALLBACK_SCHEMAS, describe_callable
    from services.mcp import tool_registry as tr

    tr.warm_catalog()
    cat = tr.catalog() or {}
    resolver = at.resolver_for(None)

    fam_tools: dict[str, list[str]] = {}
    descs: dict[str, str] = {}
    for name in sorted(cat):
        tags = cat.get(name)
        fam = (tags or {}).get("family", "?") if isinstance(tags, dict) else "?"
        fam_tools.setdefault(fam or "?", []).append(name)
        fn = None
        try:
            fn = resolver(name)
        except Exception:  # noqa: BLE001
            fn = None
        desc = ""
        if fn is not None:
            doc = (describe_callable(name, fn) or {}).get("description") or ""
            desc = _truncate(_one_line(doc.split("\n\n", 1)[0]))
        if desc:
            descs[name] = desc

    # Agent pseudo-tools (no registry callable outside a mission) live with the
    # workspace family; descriptions come from the fallback schema table.
    for name in sorted(PSEUDO_TOOLS):
        if name not in fam_tools.get("workspace", []):
            fam_tools.setdefault("workspace", []).append(name)
            fam_tools["workspace"].sort()
        if name not in descs:
            schema = _FALLBACK_SCHEMAS.get(name) or ""
            _sig, _, desc_line = schema.partition("\n")
            if desc_line.strip():
                descs[name] = _truncate(_one_line(desc_line))

    families = [f for f in DEFAULT_TOOL_FAMILIES if f in fam_tools]
    families += sorted(f for f in fam_tools if f not in families)

    # Curated tool_guidance layer (the shipping defaults the worker layers
    # under user config) — recorded so the offline header can show the same
    # prompt_note / timeout / max_calls / param_defaults when the live
    # ai_tool_catalog RPC has not answered.
    guidance: dict[str, dict] = {}
    all_names = sorted({n for tools in fam_tools.values() for n in tools})
    for name in all_names:
        entry = guidance_for(name)
        keep = {
            k: entry[k] for k in sorted(entry) if k in GUIDANCE_KEYS and entry[k]
        }
        if keep:
            guidance[name] = keep

    return {
        "families": families,
        "fam_tools": {f: fam_tools[f] for f in families},
        "descs": {k: descs[k] for k in sorted(descs)},
        "guidance": guidance,
    }


def _cstr(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def render_header(snap: dict) -> str:
    """Deterministic C++ header text from a snapshot dict (stdlib-only)."""
    out = [
        "// GENERATED by tools/gen_tool_panel_tables.py — do not edit by hand.",
        "// Offline fallback tool catalog for Settings → AI → Tools; the live view",
        "// comes from the worker ai_tool_catalog RPC whenever the runtime is up.",
        "// Data source: host/src/ui/tool_panel_tables.snapshot.json",
        "#pragma once",
        "",
        "namespace tool_panel_tables {",
        "",
        "struct FamTools { const char* fam; const char* const* tools; int n; };",
        "struct ToolDesc { const char* name; const char* desc; };",
        "struct ToolGuidance { const char* name; const char* note; int timeout_s; "
        "int max_calls; const char* param_defaults_json; };",
        "",
    ]
    for fam in snap["families"]:
        out.append(f"static const char* kTools_{fam}[] = {{")
        for name in snap["fam_tools"][fam]:
            out.append(f'    "{_cstr(name)}",')
        out.append("};")
    out.append("")
    out.append("static const FamTools kFamToolMap[] = {")
    for fam in snap["families"]:
        out.append(
            f'    {{"{fam}", kTools_{fam}, '
            f"(int)(sizeof(kTools_{fam})/sizeof(kTools_{fam}[0]))}},"
        )
    out.append("};")
    out.append(
        "static constexpr int kFamToolMapN = "
        "(int)(sizeof(kFamToolMap)/sizeof(kFamToolMap[0]));"
    )
    out.append("")
    out.append("static const ToolDesc kToolDescs[] = {")
    for name, desc in snap["descs"].items():
        out.append(f'    {{"{_cstr(name)}", "{_cstr(desc)}"}},')
    out.append("};")
    out.append(
        "static constexpr int kToolDescsN = "
        "(int)(sizeof(kToolDescs)/sizeof(kToolDescs[0]));"
    )
    out.append("")
    out.append("// Curated tool_guidance defaults (prompt_note / timeout_s /")
    out.append("// max_calls_per_turn / param_defaults). Empty string / 0 = absent.")
    out.append("static const ToolGuidance kToolGuidance[] = {")
    for name in sorted(snap.get("guidance", {})):
        g = snap["guidance"][name]
        note = _cstr(g.get("prompt_note") or "")
        timeout_s = int(g.get("timeout_s") or 0)
        max_calls = int(g.get("max_calls_per_turn") or 0)
        pd = g.get("param_defaults")
        pd_json = (
            _cstr(json.dumps(pd, sort_keys=True, separators=(",", ":")))
            if isinstance(pd, dict) and pd
            else ""
        )
        out.append(
            f'    {{"{_cstr(name)}", "{note}", {timeout_s}, {max_calls}, '
            f'"{pd_json}"}},'
        )
    out.append("};")
    out.append(
        "static constexpr int kToolGuidanceN = "
        "(int)(sizeof(kToolGuidance)/sizeof(kToolGuidance[0]));"
    )
    out.append("")
    out.append("}  // namespace tool_panel_tables")
    out.append("")
    return "\n".join(out)


def emit() -> int:
    snap = build_snapshot()
    SNAPSHOT.write_text(json.dumps(snap, indent=1, ensure_ascii=False) + "\n")
    HEADER.write_text(render_header(snap))
    total = sum(len(v) for v in snap["fam_tools"].values())
    print(f"emit: {total} tools across {len(snap['families'])} families, "
          f"{len(snap['descs'])} descriptions, "
          f"{len(snap['guidance'])} guidance entries")
    print(f"  wrote {HEADER.relative_to(REPO)}")
    print(f"  wrote {SNAPSHOT.relative_to(REPO)}")
    return 0


def check() -> int:
    if not SNAPSHOT.exists() or not HEADER.exists():
        print("FAIL tool_panel_sync: snapshot or header missing — run "
              "tools/gen_tool_panel_tables.py")
        return 1
    try:
        snap = json.loads(SNAPSHOT.read_text())
        want = render_header(snap)
    except Exception as exc:  # noqa: BLE001
        print(f"FAIL tool_panel_sync: unreadable snapshot: {exc}")
        return 1
    have = HEADER.read_text()
    if have != want:
        print("FAIL tool_panel_sync: header does not match snapshot — re-run "
              "tools/gen_tool_panel_tables.py")
        return 1
    total = sum(len(v) for v in snap.get("fam_tools", {}).values())
    print(f"PASS tool_panel_sync ({total} tools, "
          f"{len(snap.get('families', []))} families)")
    return 0


if __name__ == "__main__":
    sys.exit(check() if "--check" in sys.argv[1:] else emit())
