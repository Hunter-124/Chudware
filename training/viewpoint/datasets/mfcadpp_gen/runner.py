"""Generate many seeds in worker processes.

OCC booleans/fillets can hang or crash the interpreter (the upstream README warns about the
fillet tool), so parts are generated in `workers` child processes, one seed at a time over a
line protocol: a crashed or timed-out seed is recorded in <seed>.failed.json and its worker is
restarted; the run continues. Seeds already generated by this GENERATOR_VERSION (or recorded as
failed by it) are skipped, so a run resumes."""
from __future__ import annotations

import json
import os
import queue
import select
import subprocess
import sys
import threading
import time
from pathlib import Path
from typing import Callable, Iterable, Optional

from . import GENERATOR_VERSION, failed_path, sidecar_path, step_path

DEFAULT_TIMEOUT_S = 600.0
_REPO_ROOT = Path(__file__).resolve().parents[4]


def status(out_dir: Path, seed: int) -> Optional[dict]:
    """{"ok": True} / {"ok": False, "reason"} when this generator version already handled
    `seed` in out_dir, else None."""
    side = sidecar_path(step_path(out_dir, seed))
    if side.exists() and step_path(out_dir, seed).exists():
        try:
            if json.loads(side.read_text()).get("generator_version") == GENERATOR_VERSION:
                return {"seed": seed, "ok": True, "reason": None}
        except json.JSONDecodeError:
            return None
    fail = failed_path(out_dir, seed)
    if fail.exists():
        try:
            rec = json.loads(fail.read_text())
        except json.JSONDecodeError:
            return None
        if rec.get("generator_version") == GENERATOR_VERSION:
            return {"seed": seed, "ok": False, "reason": rec.get("reason")}
    return None


def _record_failure(out_dir: Path, seed: int, reason: str) -> dict:
    failed_path(out_dir, seed).write_text(json.dumps(
        {"seed": seed, "generator_version": GENERATOR_VERSION, "reason": reason}))
    return {"seed": seed, "ok": False, "reason": reason}


class _Worker:
    def __init__(self, out_dir: Path):
        env = dict(os.environ)
        env["PYTHONPATH"] = os.pathsep.join(
            p for p in (str(_REPO_ROOT), env.get("PYTHONPATH")) if p)
        # one BLAS thread per worker: the workers already fill the cores
        for var in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS"):
            env[var] = "1"
        self.proc = subprocess.Popen(
            [sys.executable, "-m", "training.viewpoint.datasets.mfcadpp_gen.runner", "--worker",
             str(out_dir)],
            stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
            text=True, bufsize=1, cwd=str(_REPO_ROOT), env=env)

    def run(self, seed: int, timeout_s: float) -> Optional[str]:
        """The worker's result line, or None when it died or ran past the timeout."""
        self.proc.stdin.write(json.dumps({"seed": seed}) + "\n")
        self.proc.stdin.flush()
        ready, _, _ = select.select([self.proc.stdout], [], [], timeout_s)
        if not ready:
            return None
        line = self.proc.stdout.readline()
        return line or None

    def kill(self) -> None:
        try:
            self.proc.kill()
            self.proc.wait(timeout=10)
        except (OSError, subprocess.TimeoutExpired):
            pass


def generate(seeds: Iterable[int], out_dir: Path, *, workers: int = 1,
             timeout_s: float = DEFAULT_TIMEOUT_S,
             log: Callable[[str], None] = print) -> dict:
    """Generate every seed not yet handled; returns {seed: {"ok", "reason"}} for all seeds."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    seeds = list(seeds)
    results = {}
    todo: "queue.Queue[int]" = queue.Queue()
    for s in seeds:
        st = status(out_dir, s)
        if st is None:
            todo.put(s)
        else:
            results[s] = st
    pending = todo.qsize()
    if not pending:
        return results
    lock = threading.Lock()
    done = [0]
    t0 = time.time()

    def slot() -> None:
        worker = None
        try:
            while True:
                try:
                    seed = todo.get_nowait()
                except queue.Empty:
                    return
                if worker is None or worker.proc.poll() is not None:
                    worker = _Worker(out_dir)
                line = worker.run(seed, timeout_s)
                if line is None:
                    code = worker.proc.poll()
                    worker.kill()
                    worker = None
                    reason = (f"worker exited with code {code}" if code is not None
                              else f"timeout after {timeout_s:.0f} s")
                    res = _record_failure(out_dir, seed, reason)
                else:
                    res = json.loads(line)
                with lock:
                    results[seed] = {"seed": seed, "ok": res["ok"], "reason": res["reason"]}
                    done[0] += 1
                    if done[0] % 100 == 0 or done[0] == pending:
                        log(f"  mfcadpp_gen: {done[0]}/{pending} generated "
                            f"({time.time() - t0:.0f} s)")
        finally:
            if worker is not None:
                worker.proc.stdin.close()
                worker.kill()

    threads = [threading.Thread(target=slot, daemon=True) for _ in range(max(1, workers))]
    for t in threads:
        t.start()
    for t in threads:
        t.join()
    return results


def _worker_loop(out_dir: Path) -> int:
    # OCC writes progress to fd 1 (the STEP writer's statistics); keep the protocol on a
    # private copy of stdout and send fd 1 to /dev/null
    proto = os.fdopen(os.dup(1), "w", buffering=1)
    devnull = os.open(os.devnull, os.O_WRONLY)
    os.dup2(devnull, 1)
    sys.stdout = open(os.devnull, "w")
    from .generator import write_part  # noqa: PLC0415 — OCP loads only in workers
    for line in sys.stdin:
        if not line.strip():
            continue
        seed = int(json.loads(line)["seed"])
        res = write_part(seed, out_dir)
        proto.write(json.dumps(res) + "\n")
        proto.flush()
    return 0


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--worker":
        raise SystemExit(_worker_loop(Path(sys.argv[2])))
    raise SystemExit("usage: python -m training.viewpoint.datasets.mfcadpp_gen.runner --worker DIR "
                     "(internal; use python -m training.viewpoint.datasets.mfcadpp_gen)")
