# --- Money -------------------------------------------------------------------


def split_cash(amount_cents: int, fee_bps: int) -> tuple[int, int]:
    """Split a cash amount into ``(platform_fee_cents, seller_net_cents)``.

    The fee is rounded DOWN, so the fractional cent goes to the seller and
    ``fee + net == amount_cents`` holds exactly — which is what
    ``mk_orders_split_balances`` requires. Rounding the fee up instead would
    make the platform's cut depend on the price's last digit, and there is no
    version of that which is worth explaining to a seller.
    """
    if amount_cents < 0:
        raise ValueError("amount_cents must not be negative")
    if not 0 <= fee_bps <= 10_000:
        raise ValueError("fee_bps must be between 0 and 10000")
    fee = amount_cents * fee_bps // 10_000
    return fee, amount_cents - fee


def split_credits(amount_credits: int, fee_bps: int) -> tuple[int, int]:
    """Split a credit amount into ``(platform_fee_credits, seller_net_credits)``.

    Same rounding policy as :func:`split_cash`, and the same exact-sum
    guarantee. Credits are integers by construction (1 credit == $0.001 of
    upstream model cost) so there is no sub-unit to lose.
    """
    if amount_credits < 0:
        raise ValueError("amount_credits must not be negative")
    if not 0 <= fee_bps <= 10_000:
        raise ValueError("fee_bps must be between 0 and 10000")
    fee = amount_credits * fee_bps // 10_000
    return fee, amount_credits - fee


def credits_to_cents(credits: int, credits_per_dollar: int) -> int:
    """Value of ``credits`` in cents at the given rate, rounded DOWN.

    Used only for seller cash-out, where rounding down is the conservative
    direction: the platform never pays out more than the credits were worth.
    """
    if credits < 0:
        raise ValueError("credits must not be negative")
    if credits_per_dollar <= 0:
        raise ValueError("credits_per_dollar must be positive")
    return credits * 100 // credits_per_dollar


def cents_to_credits(cents: int, credits_per_dollar: int) -> int:
    """Credits that ``cents`` buys at the given rate, rounded DOWN."""
    if cents < 0:
        raise ValueError("cents must not be negative")
    if credits_per_dollar <= 0:
        raise ValueError("credits_per_dollar must be positive")
    return cents * credits_per_dollar // 100


def suggested_price_credits(price_cents: int, credits_per_dollar: int) -> int:
    """The credit price the seller UI pre-fills beside a cash price.

    A suggestion, not a rule: a seller may price the two independently, and many
    will price credits slightly cheaper because credits cost us less to honour
    than card fees do.
    """
    return cents_to_credits(price_cents, credits_per_dollar)


# --- Text --------------------------------------------------------------------

_SLUG_STRIP = re.compile(r"[^a-z0-9]+")
_TAG_STRIP = re.compile(r"[^a-z0-9+#._-]+")


def _ascii_fold(value: str) -> str:
    """Decompose accents and drop anything that is not ASCII.

    Slugs and handles are path and URL components matched by a Postgres CHECK
    against ``^[a-z0-9]...``, so a Unicode title has to reduce to ASCII
    deterministically rather than be rejected. 'Kühlkörper' becoming
    'kuhlkorper' is a better outcome than a 400.
    """
    decomposed = unicodedata.normalize("NFKD", value)
    return decomposed.encode("ascii", "ignore").decode("ascii")


def slugify(value: str, *, max_len: int = SLUG_MAX) -> str:
    """URL slug for a listing or collection. May return ''.

    Returning '' rather than raising is deliberate: the caller knows whether an
    empty slug means "fall back to the id" (listings, which must always resolve)
    or "reject the input" (a collection the user explicitly named). Deciding here
    would force one of those to be wrong.
    """
    folded = _SLUG_STRIP.sub("-", _ascii_fold(value).lower()).strip("-")
    if not folded:
        return ""
    trimmed = folded[:max_len].rstrip("-")
    # mk_listings_slug_shape requires at least two characters and a leading
    # alphanumeric; a single character would pass the regex's first class and
    # fail its length. Pad rather than reject so a title of "V" still publishes.
    if len(trimmed) < 2:
        return (trimmed + "-0")[:max_len]
    return trimmed


def handleify(value: str) -> str:
    """Seller handle from a display name or email local part. May return ''."""
    folded = re.sub(r"[^a-z0-9_-]+", "-", _ascii_fold(value).lower()).strip("-_")
    if not folded:
        return ""
    trimmed = folded[:HANDLE_MAX].rstrip("-_")
    if len(trimmed) < 2:
        return (trimmed + "-0")[:HANDLE_MAX]
    return trimmed


def normalize_tags(raw: object) -> list[str]:
    """Canonical tag list: lower-cased, de-duplicated, order preserved, capped.

    This is the function the migration's ``search_doc`` generated column depends
    on. ``array_to_tsvector`` emits elements verbatim as lexemes with no
    normalisation of its own, so a tag that reaches the database with a capital
    letter is simply unsearchable. Every write path must pass through here.

    Accepts a list or a comma/whitespace separated string, because the upload
    form and the importers disagree about which they send and neither is wrong.
    """
    if raw is None:
        return []
    if isinstance(raw, str):
        parts: list[str] = re.split(r"[,\n]+", raw)
    elif isinstance(raw, (list, tuple)):
        parts = [str(item) for item in raw]
    else:
        return []

    out: list[str] = []
    seen: set[str] = set()
    for part in parts:
        # '+', '#', '.', '_' and '-' survive: 'x_t', 'c++', 'iso-4762' and
        # 'm3x0.5' are all real tags a CAD user types.
        tag = _TAG_STRIP.sub("-", _ascii_fold(part).lower()).strip("-.")
        if len(tag) < MIN_TAG_LEN or len(tag) > MAX_TAG_LEN:
            continue
        if tag in seen:
            continue
        seen.add(tag)
        out.append(tag)
        if len(out) >= MAX_TAGS:
            break
    return out


_CONTROL_CHARS = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")


def scrub_text(value: object) -> str:
    """Coerce untrusted input to text psycopg can actually bind.

    A NUL byte in a bound parameter makes psycopg3 raise ``DataError`` BEFORE the
    statement reaches PostgreSQL, so it surfaces as an unhandled 500 rather than
    a validation error. That was reachable anonymously across the whole
    storefront -- ``?q=``, ``?category=``, ``?seller=``, ``/suggest``, and both
    the listing and seller path parameters -- and on every authenticated text
    body field. PostgreSQL cannot store NUL in a ``text`` column at all, so there
    is nothing to preserve: stripping it is strictly better than 500ing, and
    strictly better than rejecting, because a scrubbed slug simply fails to match
    and yields an honest 404.

    Other C0 controls go too. Tab, newline and carriage return are kept because a
    listing description legitimately contains them.
    """
    return _CONTROL_CHARS.sub("", str(value or ""))


def to_tsquery_text(query: str) -> str:
    """Turn a user's search box into a safe ``websearch_to_tsquery`` argument.

    ``websearch_to_tsquery`` already tolerates arbitrary text — it never raises
    the way ``to_tsquery`` does on unbalanced operators — so the only work left
    is scrubbing unbindable bytes, bounding the length and collapsing
    whitespace. Keeping quotes and ``-`` is the point: they are the phrase and
    negation syntax users expect.
    """
    return re.sub(r"\s+", " ", scrub_text(query)).strip()[:200]


# --- Provenance --------------------------------------------------------------


def attestation_required(origin: str) -> bool:
    """Whether claiming ``origin`` obliges the seller to file an attestation.

    Only the human-made claim is gated. Disclosing AI involvement costs the
    seller nothing to be honest about, so demanding paperwork for it would only
    push people toward the unverifiable claim — exactly backwards.
    """
    return origin == "human"


def human_shelf_eligible(origin: str, attestation_status: str) -> bool:
    """Whether a listing may appear on the human-made shelf.

    An unverified human claim is shown on its own listing page with its
    disclosure, but it does not reach the curated shelf: the shelf's entire
    value is that someone checked.
    """
    return origin == "human" and attestation_status == "verified"


def derive_open_source(*, license_is_open_source: bool, pricing_kind: str) -> bool:
    """The single definition of ``mk_listings.open_source``.

    Both halves matter. An open license on a paid listing is legal but is not
    what a visitor filtering for open source is looking for, and a free download
    under an all-rights-reserved license is not open source at all. The database
    enforces only the free half (``mk_listings_open_source_is_free``) because the
    license half needs a join it cannot do in a CHECK.
    """
    return bool(license_is_open_source) and pricing_kind == "free"


# --- Keyset pagination -------------------------------------------------------


class CursorError(ValueError):
    """A cursor that did not decode. Callers map this to HTTP 400."""


# Per-sort key types, mirroring each entry in SORT_ORDERS. Admin list routes mint
# their own sort names, so anything absent from this table is refused outright
# rather than defaulted -- a new sort must declare its key shape to be usable.
_CURSOR_KEY_TYPES: Final[dict[str, tuple[str, ...]]] = {
    "newest": ("ts", "uuid"),
    "oldest": ("ts", "uuid"),
    "downloads": ("int", "uuid"),
    "popular": ("int", "uuid"),
    "rating": ("num", "int", "uuid"),
    "price_low": ("int", "int", "uuid"),
    "price_high": ("int", "int", "uuid"),
    "relevance": ("num", "ts", "uuid"),
    # Admin queues, keyed (timestamp, id).
    "admin_listings": ("ts", "uuid"),
    "admin_attestations": ("ts", "uuid"),
    "admin_reports": ("ts", "uuid"),
    "admin_sellers": ("ts", "str"),
    "admin_payouts": ("ts", "uuid"),
    "admin_imports": ("ts", "uuid"),
    "admin_subscriptions": ("ts", "str"),
    "studio_listings": ("ts", "uuid"),
    "orders": ("ts", "uuid"),
    "reviews": ("ts", "uuid"),
}

_UUID_RE = re.compile(
    r"^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-"
    r"[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$"
)
# Enough to accept anything PostgreSQL emitted for a timestamptz, and nothing
# resembling an injection or an unbounded string.
_TS_RE = re.compile(r"^[0-9]{4}-[0-9]{2}-[0-9]{2}[ T][0-9:.+\-]{4,20}(Z)?$")


def _cursor_key_ok(value: object, kind: str) -> bool:
    if kind == "uuid":
        return isinstance(value, str) and bool(_UUID_RE.match(value))
    if kind == "ts":
        # NULL is legitimate: 'newest' sorts published_at DESC NULLS LAST, and a
        # seller's own draft list legitimately pages past unpublished rows.
        return value is None or (isinstance(value, str) and bool(_TS_RE.match(value)))
    if kind == "int":
        return isinstance(value, int) and not isinstance(value, bool) and -(2**63) < value < 2**63
    if kind == "num":
        return (
            isinstance(value, (int, float))
            and not isinstance(value, bool)
            and math.isfinite(value)
        )
    if kind == "str":
        return isinstance(value, str) and 0 < len(value) <= 320
    return False


def encode_cursor(sort: str, keys: Sequence[object]) -> str:
    """Opaque cursor for the last row of a page.

    The sort name travels inside the cursor so a client that changes the sort
    while holding an old cursor gets a clean 400 instead of a page assembled
    from a comparison against the wrong column. ``keys`` are the values of that
    sort's ORDER BY expressions for the final row, ending with the row id.

    base64url of compact JSON: short enough for a query string, and opaque
    enough that nobody builds a client that parses it.
    """
    payload = json.dumps({"s": sort, "k": list(keys)}, separators=(",", ":"), default=str)
    return base64.urlsafe_b64encode(payload.encode("utf-8")).decode("ascii").rstrip("=")


def decode_cursor(cursor: str, *, expect_sort: str) -> list[object]:
    """Inverse of :func:`encode_cursor`. Raises :class:`CursorError`.

    Every failure mode is one exception with no detail: a cursor is server-minted
    and a malformed one is either a bug or someone probing, and neither deserves
    a message describing the format.
    """
    padded = cursor + "=" * (-len(cursor) % 4)
    try:
        raw = base64.urlsafe_b64decode(padded.encode("ascii"))
        payload = json.loads(raw)
    except (ValueError, TypeError) as exc:
        raise CursorError("malformed cursor") from exc
    if not isinstance(payload, dict) or payload.get("s") != expect_sort:
        raise CursorError("cursor does not match this sort order")
    keys = payload.get("k")
    if not isinstance(keys, list) or not keys:
        raise CursorError("malformed cursor")
    # A cursor is spliced into a WHERE clause as bound parameters, never as text,
    # but binding is not validation. The keys are compared against typed columns
    # -- bigint counters, numeric ratings, timestamptz, uuid -- so a forged
    # cursor like `["not-a-bigint", "not-a-uuid"]` for the `downloads` sort is
    # accepted by the checks above, reaches PostgreSQL, fails the cast, and
    # returns 500 where the documented answer is a 400. Type-check here so a
    # hostile cursor cannot reach the planner at all.
    if len(keys) != len(_CURSOR_KEY_TYPES.get(expect_sort, ())):
        raise CursorError("malformed cursor")
    for value, kind in zip(keys, _CURSOR_KEY_TYPES[expect_sort]):
        if not _cursor_key_ok(value, kind):
            raise CursorError("malformed cursor")
    return keys


def clamp_limit(raw: object, *, default: int = PAGE_SIZE_DEFAULT) -> int:
    """Page size from an untrusted query parameter.

    Silently clamps rather than rejecting: a client asking for 10000 rows wants
    as many as it can have, and failing its request teaches it nothing it can
    act on.
    """
    try:
        value = int(raw)  # type: ignore[arg-type]
    except (TypeError, ValueError):
        return default
    return max(1, min(value, PAGE_SIZE_MAX))


