"""Shared marketplace vocabulary, money math, and text normalisation.

Every marketplace module imports from here rather than restating a constant, so
there is exactly one definition of what a status is, how a fee splits, and what
a tag looks like after normalisation. Nothing in this module performs I/O: it is
pure data and pure functions, which is what makes it safe for the API layer, the
render pipeline, the importers, the admin surface and the tests to share.

Two invariants are load-bearing and easy to break by accident:

* **The vocabularies mirror 0016_marketplace.sql exactly.** Each tuple below has
  a database CHECK constraint behind it. Adding a member here without a
  migration produces a 500 at insert time, not a validation error, so the pairs
  are named in comments and asserted by
  ``tests/test_marketplace.py::test_vocabularies_match_database_constraints``.

* **Fee splits never lose or invent a unit.** ``split_cash`` and
  ``split_credits`` both return ``(fee, net)`` where ``fee + net == amount``
  exactly, because ``mk_orders_split_balances`` checks that in the database.
  Rounding always favours the seller — the platform absorbs the sub-cent — which
  is a deliberate policy choice and not an accident of ``//``.

Pagination is keyset, not OFFSET: the grid is sorted by counters that change
while a visitor scrolls, and OFFSET silently duplicates and skips rows when they
do. ``encode_cursor``/``decode_cursor`` live here rather than in a route module
so the browse endpoint, the seller studio and the admin lists all produce and
accept the same cursor.
"""

